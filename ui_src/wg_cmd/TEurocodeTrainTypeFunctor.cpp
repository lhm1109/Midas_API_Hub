int TEurocodeTrainTypeFunctor::GetTypeB(UINT unForceNumber, 
                                        double dSpace, 
                                        vPaird& rvLF) const
{
    //Figure 6.13 - HSLM-B 참고
    const auto dForceKN = 170.0;
    rvLF.push_back(std::make_pair(0.0, dForceKN)); //맨 좌측 초기값

    for ( UINT unIdx = 0U; unIdx < unForceNumber; ++unIdx )
    {
        rvLF.push_back(std::make_pair(dSpace, dForceKN)); //등 간격 추가
    }

    return static_cast<int>(rvLF.size());
}